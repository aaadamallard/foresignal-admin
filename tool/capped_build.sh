#!/bin/sh
# Runs a build command under a hard memory cap, then leaves no Gradle or Kotlin daemon behind.
#
#   tool/capped_build.sh flutter build apk --release
#   tool/capped_build.sh flutter build appbundle --release
#
# The command runs in a systemd user scope, foresignal-admin-build.scope, with MemoryMax
# (FORESIGNAL_BUILD_MEM_MAX, default 11G) and MemorySwapMax=0. Everything it starts, the Gradle
# daemon and the Kotlin compiler daemon included, is inside the cap and cannot swap, so a build
# that outgrows it is OOM-killed instead of thrashing the host. On 2026-10-25 two uncapped 8 GB
# Gradle daemons, one left behind by a rejected command, helped fill 24 GB of swap and the host
# had to be power-cycled.
#
# 11G because a release APK build needs it: at 8G the Dart frontend_server reached 7 GB and the
# build was OOM-killed; at 11G it finished. An 11G build beside the 7.5 GiB server is more than
# the host's 23 GiB of RAM, so do not build while the server runs; earlyoom covers an accident.
#
# Before the command, ./gradlew --stop ends any daemon started outside the cap, which the build
# would otherwise reuse. Afterwards, on success, failure or interrupt, ./gradlew --stop runs again
# and the scope is stopped, which kills whatever is still in it. The command's exit status is the
# script's. There is no uncapped mode: without a systemd user manager the script refuses to run,
# and inside the scope, before the command starts, it exits 125 unless the scope's memory.max and
# memory.swap.max are what was asked for.
set -eu

cd "$(dirname "$0")/.."
UNIT=foresignal-admin-build.scope
MEM_MAX=${FORESIGNAL_BUILD_MEM_MAX:-11G}

fail() {
  printf 'capped_build: %s\n' "$1" >&2
  exit 1
}

# Converts a K, M or G size to bytes, as systemd writes it to memory.max.
to_bytes() {
  n=${1%?}
  case $1 in
    *K) echo $((n * 1024)) ;;
    *M) echo $((n * 1024 * 1024)) ;;
    *G) echo $((n * 1024 * 1024 * 1024)) ;;
  esac
}

is_active() {
  [ "$(systemctl --user show -p ActiveState --value "$UNIT" 2>/dev/null)" = active ]
}

# Stops this project's Gradle daemons; gradlew is generated by Flutter and may not exist yet.
stop_daemons() {
  if [ -x android/gradlew ]; then
    (cd android && ./gradlew --stop -q) || true
  fi
}

# Stops the daemons, then the scope and anything still in it.
cleanup() {
  stop_daemons
  systemctl --user stop "$UNIT" >/dev/null 2>&1 || true
  systemctl --user reset-failed "$UNIT" >/dev/null 2>&1 || true
}

[ $# -gt 0 ] || fail "usage: tool/capped_build.sh <command> [args...]"
expr "$MEM_MAX" : '[1-9][0-9]*[KMG]$' >/dev/null \
  || fail "FORESIGNAL_BUILD_MEM_MAX must be a whole number of K, M or G, not '$MEM_MAX'"
command -v systemd-run >/dev/null || fail "systemd-run is missing; refusing to build uncapped"
systemctl --user show-environment >/dev/null 2>&1 \
  || fail "no systemd user manager; refusing to build uncapped"
is_active && fail "$UNIT is already running: one capped build at a time"

stop_daemons
systemctl --user reset-failed "$UNIT" >/dev/null 2>&1 || true
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# The cap is checked from inside the scope, before the command replaces the checking shell.
status=0
systemd-run --user --scope --unit="$UNIT" --quiet \
  -p MemoryMax="$MEM_MAX" -p MemorySwapMax=0 \
  sh -c '
    dir=/sys/fs/cgroup$(cut -d: -f3 /proc/self/cgroup)
    max=$(cat "$dir/memory.max"); swap=$(cat "$dir/memory.swap.max")
    if [ "$max" != "$1" ] || [ "$swap" != 0 ]; then
      echo "capped_build: the cap did not apply (memory.max=$max, memory.swap.max=$swap)" >&2
      exit 125
    fi
    shift
    echo "capped_build: $* (memory.max=$max bytes, memory.swap.max=0)" >&2
    exec "$@"
  ' capped_build "$(to_bytes "$MEM_MAX")" "$@" || status=$?
exit "$status"
